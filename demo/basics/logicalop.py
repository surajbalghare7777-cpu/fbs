#1. and: if both operand are true, then the condition becomes true,else it is false
print(True and True)  # True   
print(True and False) # False

#2. or: if any of the operand is true, then the condition becomes true, else it is false
# other statement: if both operand are false, then the condition becomes false,else it is true
print(False or False) #False
print(False or True) #True

#3.not: used to reverse the logical state of its operand. if a condition is true, then the not operator will make it false
#it shows opposite of operand
print(not True)  # False
print(not False) # True
